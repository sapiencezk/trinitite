static int equal(const uint8_t *a, const uint8_t *b)
{
    uint8_t diff = 0;
    for (unsigned i = 0; i < 32; i++) diff |= a[i] ^ b[i];
    return diff == 0;
}

int m25_admission_program_known(const uint8_t program_hash[32])
{
    if (!program_hash) return 0;
    return equal(M25_CATALOG[0].program, program_hash)
        || equal(M25_CATALOG[1].program, program_hash);
}

int m25_admission_lookup(const uint8_t program_hash[32],
                         const uint8_t executable_anchor[32],
                         const uint8_t pill_digest[32],
                         const uint8_t limits_hash[32],
                         const i2_admission_catalog_entry_t **out)
{
    if (!program_hash || !executable_anchor || !pill_digest) return 0;
    const m25_entry_t *found = 0;
    unsigned matches = 0;
    for (unsigned i = 0; i < 2; i++) {
        const m25_entry_t *entry = &M25_CATALOG[i];
        if (equal(entry->program, program_hash)
            && equal(entry->anchor, executable_anchor)
            && equal(entry->pill, pill_digest)
            && (!limits_hash || equal(entry->limits, limits_hash))) {
            found = entry;
            matches++;
        }
    }
    if (matches != 1) return 0;
    /* The caller only uses the pointer as an admission witness.  The M25
     * catalog's private row type is intentionally not exposed as a second
     * target policy API. */
    if (out) *out = (const i2_admission_catalog_entry_t *)(uintptr_t)found;
    return 1;
}
