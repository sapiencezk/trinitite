static int descriptor_id_equal(const uint8_t left[32], const uint8_t right[32])
{
    uint8_t difference = 0;
    for (size_t i = 0; i < 32; ++i) {
        difference |= (uint8_t)(left[i] ^ right[i]);
    }
    return difference == 0;
}

const M38ResourceCoreDescriptor *m38_resource_core_descriptor(
    const uint8_t core_id[32])
{
    if (!core_id) {
        return 0;
    }
    for (size_t i = 0; i < M38_RESOURCE_CORE_COUNT; ++i) {
        if (descriptor_id_equal(core_id, descriptors[i].core_id)) {
            return &descriptors[i];
        }
    }
    return 0;
}
