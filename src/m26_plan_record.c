int m26_plan_record_validate(void)
{
    return m26_admitted_plan.source_device_id != m26_admitted_plan.target_device_id
        && m26_admitted_plan.source_resource_id != m26_admitted_plan.target_resource_id
        && m26_admitted_plan.publish_instance != m26_admitted_plan.subscribe_instance
        && m26_admitted_plan.source_application_instance == 5
        && m26_admitted_plan.target_application_instance == 5
        && m26_admitted_plan.epoch == 1 && m26_admitted_plan.key_id == 1
        && m26_admitted_plan.source_event[0] != m26_admitted_plan.source_event[1]
        && m26_admitted_plan.source_data[0] != m26_admitted_plan.source_data[1];
}

int m26_plan_record_source_association(uint64_t event, uint64_t ordinal,
                                       uint64_t data)
{
    for (unsigned i = 0; i < 2; i++)
        if (event == m26_admitted_plan.source_event[i]
            && ordinal == m26_admitted_plan.source_ordinal[i]
            && data == m26_admitted_plan.source_data[i]) return 1;
    return 0;
}
